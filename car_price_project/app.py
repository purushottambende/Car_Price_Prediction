MODELS_DIR = ROOT / "models"
ASSETS_DIR = ROOT / "assets"
MODEL_VERSION = "v2.0_2024"  # Update this to force cache reload


@st.cache_resource(show_spinner="Loading models…")
def load_models(version=MODEL_VERSION):
    import joblib
    reg = joblib.load(MODELS_DIR / "regressor.joblib")
    clf = joblib.load(MODELS_DIR / "classifier.joblib")
    with open(MODELS_DIR / "metadata.json") as f:
        meta = json.load(f)
    return reg, clf, meta


def models_exist() -> bool:
    return (
        (MODELS_DIR / "regressor.joblib").exists()
        and (MODELS_DIR / "classifier.joblib").exists()
        and (MODELS_DIR / "metadata.json").exists()
    )


# ══════════════════════════════════════════════════════════════════════════════
# HELPER FUNCTIONS
# ══════════════════════════════════════════════════════════════════════════════
def format_inr(lakhs: float) -> str:
    """Format price in Indian rupee notation."""
    rupees = int(round(abs(lakhs) * 1e5))
    s = str(rupees)
    if len(s) <= 3:
        formatted = s
    else:
        formatted = s[-3:]
        s = s[:-3]
        while s:
            formatted = s[-2:] + "," + formatted
            s = s[:-2]
    sign = "-" if lakhs < 0 else ""
    return f"₹ {sign}{formatted}"


def deal_rating_html(predicted: float, listed: float) -> str:
    if listed <= 0 or predicted <= 0:
        return ""
    ratio = (listed - predicted) / predicted
    if ratio < -0.10:
        return '<span class="deal-good">Good deal — priced more than 10% below market</span>'
    elif ratio <= 0.10:
        return '<span class="deal-fair">Fair deal — priced within ±10% of market</span>'
    else:
        return '<span class="deal-over">Overpriced — more than 10% above market</span>'


def cat_badge(cat: str) -> str:
    cls = {"Low": "cat-low", "Medium": "cat-medium", "High": "cat-high"}.get(cat, "")
    return f'<span class="cat-badge {cls}">{cat}</span>'


def summary_html(rows: list[tuple[str, str]]) -> str:
    items = "".join(
        f'<div class="summary-item"><div class="k">{k}</div><div class="v">{v}</div></div>'
        for k, v in rows
    )
    return f'<div class="summary-grid">{items}</div>'


